import React, { useState } from 'react';
import { ShieldCheck, ShieldAlert, AlertTriangle, Copy, Check, FileCheck } from 'lucide-react';

export default function ActionRecommendations({ result = {}, recommendations: propRecs, verdict: propVerdict, emailData = {} }) {
  const [copied, setCopied] = useState(false);
  
  const verdict = propVerdict || result.verdict || 'phishing';
  const recommendations = propRecs || result.recommendations || [];

  const generateReportText = () => {
    return `=== EMAIL THREAT INCIDENT REPORT ===
Date: ${new Date().toISOString()}
Verdict: ${(result.verdictTitle || verdict).toUpperCase()}
Risk Score: ${result.score || 'N/A'}%
Model Certainty: ${result.confidence || 'N/A'}%

--- SENDER ENVELOPE ---
From: ${emailData.senderName || 'N/A'} <${emailData.senderEmail || 'N/A'}>
Subject: ${emailData.subject || 'N/A'}

--- IDENTIFIED RED FLAGS ---
${(result.redFlags || []).map((f, i) => `${i + 1}. [${(f.severity || 'HIGH').toUpperCase()}] ${f.title || f}: ${f.description || ''}`).join('\n')}

--- RECOMMENDED INCIDENT ACTIONS ---
${recommendations.map((r, i) => `${i + 1}. ${r.title} - ${r.details}`).join('\n')}

Generated by Zero-Day PhishShield Enterprise
`;
  };

  const handleCopyReport = () => {
    navigator.clipboard.writeText(generateReportText());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-6 transition-colors duration-200">
      <div className="bg-slate-50 dark:bg-[#090D16] border border-slate-200 dark:border-white/10 rounded-2xl p-5 shadow-xs">
        <div className="flex items-center justify-between mb-4 pb-3 border-b border-slate-200 dark:border-white/10">
          <div className="flex items-center space-x-2">
            {verdict === 'phishing' ? (
              <ShieldAlert className="w-4 h-4 text-rose-500" />
            ) : verdict === 'suspicious' ? (
              <AlertTriangle className="w-4 h-4 text-amber-500" />
            ) : (
              <ShieldCheck className="w-4 h-4 text-emerald-500" />
            )}
            <h4 className="text-xs font-mono font-bold uppercase tracking-wider text-slate-800 dark:text-slate-200">
              Recommended Security Response Playbook
            </h4>
          </div>

          <button
            type="button"
            onClick={handleCopyReport}
            className="flex items-center space-x-1.5 px-3 py-1.5 rounded-xl bg-white dark:bg-slate-900 hover:bg-slate-100 dark:hover:bg-slate-800 text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white text-xs font-mono font-medium border border-slate-200 dark:border-white/10 transition-colors shadow-xs cursor-pointer"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-500" />
                <span className="text-emerald-600 dark:text-emerald-400 font-bold">Copied Incident Report</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Incident Summary</span>
              </>
            )}
          </button>
        </div>

        <div className="space-y-3">
          {recommendations.map((rec, idx) => (
            <div
              key={idx}
              className="p-3.5 rounded-xl bg-white dark:bg-[#0F172A] border border-slate-200 dark:border-white/10 flex items-start space-x-3 shadow-xs"
            >
              <div className="w-5 h-5 rounded-md bg-blue-500/10 border border-blue-500/20 text-blue-600 dark:text-blue-400 flex items-center justify-center shrink-0 mt-0.5 font-mono text-[11px] font-bold">
                {idx + 1}
              </div>
              <div>
                <h5 className="text-xs font-bold text-slate-900 dark:text-slate-100">
                  {rec.title}
                </h5>
                <p className="text-xs text-slate-600 dark:text-slate-400 mt-1 leading-relaxed">
                  {rec.details}
                </p>
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
